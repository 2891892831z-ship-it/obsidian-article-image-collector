function resolveLanguage(preference='auto',host='zh') {
  if(preference==='zh'||preference==='en')return preference;
  return /^zh(?:[-_]|$)/i.test(host||'zh')?'zh':'en';
}
const patterns=Object.entries(messages).filter(([key])=>/\{\d+\}/.test(key)).map(([key,value])=>{
  const indices=[];
  const pattern=key.split(/(\{\d+\})/).map(part=>{
    if(/^\{\d+\}$/.test(part)){indices.push(Number(part.slice(1,-1)));return '([\\s\\S]*?)';}
    return part.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
  }).join('');
  return {regex:new RegExp('^'+pattern+'$'),indices,value};
});
function translate(message,language='zh',...args) {
  let output=message;
  if(language==='en') {
    if(Object.prototype.hasOwnProperty.call(messages,message))output=messages[message];
    else for(const {regex,indices,value} of patterns){const match=regex.exec(message);if(match){const values={};indices.forEach((id,i)=>values[id]=match[i+1]);return value.replace(/\{(\d+)\}/g,(whole,id)=>values[id]??whole);}}
  }
  return output.replace(/\{(\d+)\}/g,(whole,id)=>args[id]===undefined?whole:String(args[id]));
}
